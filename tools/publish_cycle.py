def gzip_into(src, dst):
    """Reproducible gzip: no file name, mtime 0."""
    with open(src, "rb") as f, open(dst, "wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, compresslevel=9, mtime=0) as gz:
            shutil.copyfileobj(f, gz, 1 << 20)


def _member(path, content_of=None, note=None):
    m = {"sha256": ca.sha256_file(path), "size": path.stat().st_size}
    if content_of is not None:
        m["content_sha256"], m["content_size"] = ca.sha256_file(content_of), content_of.stat().st_size
    if note:
        m["note"] = note
    return m


def closure_members(facts, tmp, closure=None, require=False):
    """The closure graph (when the receipt names one) and report (when there is one) into
    TMP: ({member: record}, component record)."""
    import closure_report as cr
    members = {}
    if facts["graph"] is not None:
        shutil.copyfile(facts["graph"], tmp / ca.CLOSURE_GRAPH)
        members[ca.CLOSURE_GRAPH] = _member(tmp / ca.CLOSURE_GRAPH,
                                            note="as link_cycle wrote it; bound by the receipt's closure_graph_sha256")
    src = Path(closure) if closure else facts["run_dir"]
    roots, table = src / cr.ROOTS, src / cr.BLOCKERS
    if not (roots.is_file() and table.is_file()):
        if closure:
            raise RunError(f"--closure {src}: no {cr.ROOTS} and {cr.BLOCKERS}")
        how = "graph" if facts["graph"] is not None else "replay"
        if require:
            raise RunError(f"{src} holds no closure report ({cr.ROOTS}, {cr.BLOCKERS}): run python3 "
                           f"tools/closure_report.py {how} first, or pass --diagnostic-only to publish this "
                           "measurement without one (the closure queue then keeps serving the last bundle that has "
                           "a report)")
        return members, {"included": False, "status": "diagnostic-only",
                         "why": f"published diagnostic-only: the run directory holds no {cr.ROOTS} and "
                                f"{cr.BLOCKERS} (tools/closure_report.py {how})"}
    try:
        doc = cr.load_roots(roots)
    except cr.ReportError as e:
        raise RunError(str(e)) from None
    gzip_into(roots, tmp / ca.CLOSURE_ROOTS)
    gzip_into(table, tmp / ca.CLOSURE_BLOCKERS)
    members.update({ca.CLOSURE_ROOTS: _member(tmp / ca.CLOSURE_ROOTS, roots, "see components.closure_report"),
                    ca.CLOSURE_BLOCKERS: _member(tmp / ca.CLOSURE_BLOCKERS, table,
                                                 "content bound by closure_roots.json's blockers.sha256")})
    return members, {"included": True, "schema": doc["schema"], "algorithm": doc["algorithm"],
                     "source": doc.get("source"), "graph": doc["graph"]["label"], "tool": doc.get("tool"),
                     "checks": doc.get("checks"),
                     "scored_roots_with_gain": doc["summary"]["scored_roots_with_gain"]}


def cycle_diff_member(facts, tmp, previous=None, first=False):
    """Write cycle_diff.json into TMP when asked and possible: ({member: record}, component record)."""
    if previous and first:
        raise RunError("--previous and --first exclude each other")
    if not previous and not first:
        return {}, {"included": False, "why": "no --previous run and no --first given"}
    cd = cycle_diff_module()
    if cd is None:
        return {}, {"included": False, "why": "tools/cycle_diff.py is not in the producer's checkout"}
    if previous and (Path(previous) / ca.MANIFEST).is_file():
        try:                                      # a fetched bundle: only a valid one is a predecessor
            ca.validate(previous, recompute_core=False)
        except ca.BundleError as e:
            raise RunError(f"--previous {previous}: {e}") from None
    try:
        report = cd.compare(str(previous) if previous else None, str(facts["run_dir"]))
    except cd.CycleDiffError as e:
        raise RunError(f"cycle_diff refused the comparison: {e}") from None
    new, old = report["identity"]["new"], report["identity"]["old"]
    if (new.get("commit"), new.get("core_sha256")) != (facts["commit"], facts["core"]):
        raise RunError("cycle_diff's NEW run is not this run")
    pred = None
    if previous:
        try:
            raw = (Path(previous) / "receipt.json").read_bytes()
            was = json.loads(raw)
            pred = {"commit": old.get("commit"), "core_sha256": old.get("core_sha256"), "tag": ca.tag_for(raw),
                    "receipt_sha256": hashlib.sha256(raw).hexdigest(),
                    "measured_end_utc": ca.measured_of(was)["end_utc"]}
        except (OSError, ValueError, ca.BundleError) as e:
            raise RunError(f"--previous {previous}: no readable receipt.json ({e})") from None
        if (was.get("commit"), was.get("core_sha256")) != (pred["commit"], pred["core_sha256"]):
            raise RunError(f"--previous {previous}: its receipt.json is not the run cycle_diff compared")
        if pred["receipt_sha256"] == hashlib.sha256(facts["receipt_bytes"]).hexdigest():
            raise RunError(f"--previous {previous} is this measurement itself")
        if ca.parse_utc(pred["measured_end_utc"]) > ca.parse_utc(facts["measured"]["end_utc"]):
            raise RunError(f"--previous {previous} was measured after this run ({pred['measured_end_utc']}): a "
                           "predecessor is an EARLIER published measurement")
    (tmp / ca.CYCLE_DIFF).write_text(cd.dumps(report), encoding="utf-8", newline="\n")
    totals = report.get("totals") if report.get("comparison") else None
    return ({ca.CYCLE_DIFF: _member(tmp / ca.CYCLE_DIFF, note="see components.cycle_diff")},
            {"included": True, "schema_version": report["schema_version"], "comparison": bool(report["comparison"]),
             "predecessor": pred, "totals": totals,
             "tool": {"path": "tools/cycle_diff.py", "text_sha256": ca.text_sha256(cd.__file__)},
             "serializer": "cycle_diff.dumps"})


def make_bundle(run_dir, out, producer, *, rank="auto", snapshot_root=None, rank_objects=None, root=ROOT,
                now=None, python=None, closure=None, previous=None, first=False, require_closure=False):
    """Write the bundle for RUN_DIR at OUT; returns its manifest. REQUIRE_CLOSURE (the CLI's
    default, lifted by --diagnostic-only) refuses a run with no closure report."""
    if not (producer or "").strip():
        raise RunError("a producer label is required (--producer host/user)")
    if rank not in RANK_MODES:
        raise RunError(f"--rank {rank!r}: one of {', '.join(RANK_MODES)}")
    facts = validate_run(run_dir, root=root)
    out = Path(out)
    if out.exists() and (not out.is_dir() or any(out.iterdir())):
        raise RunError(f"{out} exists: a bundle is immutable; choose a new --out")
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix=f".{out.name}.partial-", dir=out.parent))
    try:
        (tmp / ca.RECEIPT).write_bytes(facts["receipt_bytes"])
        gzip_into(facts["status"], tmp / ca.LINK_STATUS)
        gzip_into(facts["folds"], tmp / ca.DATA_FOLDS)
        with tempfile.TemporaryDirectory(prefix="publish_cycle-") as work:
            inputs = measured_inputs(facts, work, snapshot_root=snapshot_root, root=root)
            analysis = rank_report(facts, inputs, tmp, work, mode=rank, objects=rank_objects, python=python)
        receipt = facts["receipt"]
        members = {
            ca.RECEIPT: _member(tmp / ca.RECEIPT, note="as link_cycle wrote it; its core is receipt.core_sha256"),
            ca.LINK_STATUS: _member(tmp / ca.LINK_STATUS, facts["status"],
                                    "content bound by the receipt's series.link_status_sha256"),
            ca.DATA_FOLDS: _member(tmp / ca.DATA_FOLDS, facts["folds"],
                                   "written by the same measure; the receipt records no hash for it"),
            ca.RANK_TXT: _member(tmp / ca.RANK_TXT, note="see analysis.data_back_rank"),
            ca.RANK_JSON: _member(tmp / ca.RANK_JSON, note="see analysis.data_back_rank"),
        }
        closure_m, closure_c = closure_members(facts, tmp, closure, require_closure)
        diff_m, diff_c = cycle_diff_member(facts, tmp, previous, first)
        members.update(closure_m)
        members.update(diff_m)
        rules = {"rules": facts["rules"], "shadow_rules": facts["shadow_rules"], "canon_rules": facts["canon_rules"]}
        bundle_tool = ca.text_sha256(Path(__file__))
        manifest = {
            "schema": ca.SCHEMA,
            "tag": ca.tag_for(facts["receipt_bytes"]),
            "instance": {"measured_end_utc": facts["measured"]["end_utc"],
                         "receipt_sha256": hashlib.sha256(facts["receipt_bytes"]).hexdigest()},
            "commit": facts["commit"],
            "submodules": facts["submodules"],
            "bfme1_pointer": facts["bfme1_pointer"],
            "producer": producer.strip(),
            "created_utc": ca.iso_utc(time.time() if now is None else now),
            "measured": facts["measured"],
            "receipt": {"core_sha256": facts["core"], "core_canon_sha256": facts["core_canon"],
                        "authoritative": True, "tree_manifest": receipt.get("tree_manifest"),
                        "closure_graph_sha256": receipt.get("closure_graph_sha256"),
                        "link_status_sha256": facts["status_sha256"], "core_check": facts["core_check"]},
            "rules": dict(rules, digest=ca.digest_of(rules)),
            "tool_digest": facts["tool_digest"],
            "components": {"closure_report": closure_c, "cycle_diff": diff_c},
            "analysis": {"digest": ca.digest_of({"bundle_tool": bundle_tool, "data_back_rank": analysis,
                                                 "closure_report": closure_c.get("tool"),
                                                 "cycle_diff": diff_c.get("tool")}),
                         "bundle_tool": {"path": "tools/publish_cycle.py", "text_sha256": bundle_tool},
                         "data_back_rank": analysis},
            "diagnostic_inputs": {"basis": inputs["basis"], "cross_check": inputs["cross_check"],
                                  "hash": "text_sha256: sha256 of the text with CRLF read as LF "
                                          "(link_cycle.text_sha256)",
                                  "files": inputs["files"]},
            "headline": ca.headline_of(receipt),
            "members": members,
        }
        (tmp / ca.MANIFEST).write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n", encoding="utf-8",
                                       newline="\n")
        ca.validate(tmp, root=root)
        os.chmod(tmp, 0o755)                     # mkdtemp's 0700 would follow the rename
        if out.exists():
            out.rmdir()
        tmp.rename(out)
    except BaseException:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    return manifest


