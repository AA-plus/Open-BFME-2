def shown(args):
    return "gh " + " ".join(shlex.quote(a) for a in args)


def user_cmd():
    return ["api", "user"]


def immutable_cmd(repo):
    return ["api", f"repos/{repo}/immutable-releases"]


def releases_of(gh, repo, tag):
    """Every release (drafts included) holding TAG."""
    return [r for r in ca.list_releases(gh, repo) if r.get("tag_name") == tag]


def asset_digests(release):
    return {a.get("name"): str(a.get("digest") or "") for a in release.get("assets") or ()}


def same_assets(release, files):
    """The release's assets are byte for byte FILES, by the release API's SHA-256 digests."""
    return asset_digests(release) == {f.name: "sha256:" + ca.sha256_file(f) for f in files}


def title_of(manifest):
    credit = (manifest.get("headline") or {}).get("credit_unique_bytes")
    return (f"link_cycle {manifest['commit'][:12]}: credit "
            + (f"{credit:,} B" if isinstance(credit, int) else "?")
            + f" (measured {manifest['measured']['end_utc']})")


def release_notes(manifest):
    """Text for people. Nothing reads it back: consumers authenticate the release by its
    author, its immutability, its tag and the asset digests of the release API."""
    h = manifest.get("headline") or {}
    num = (lambda v: f"{v:,}" if isinstance(v, int) else "?")
    rank = manifest["analysis"]["data_back_rank"]
    m = manifest["measured"]
    return "\n".join([
        f"`{manifest['tag']}`: link_cycle measurement of `{manifest['commit']}` (receipt core "
        f"`{manifest['receipt']['core_sha256'][:16]}`, receipt sha256 `{manifest['instance']['receipt_sha256'][:16]}`).",
        "",
        f"- measured {m.get('start_utc')} .. {m.get('end_utc')} by {manifest['producer']}; rules "
        f"{manifest['rules']['rules']} (shadow: {', '.join(manifest['rules']['shadow_rules']) or 'none'}); "
        "authoritative receipt",
        f"- credit (placed closed-strict real unique bytes) {num(h.get('credit_unique_bytes'))}; self-strict "
        f"{num(h.get('real_placed_self_strict_unique_bytes'))}; placed {num(h.get('real_placed_unique_bytes'))}",
        f"- link_cycle tool digest `{manifest['tool_digest'][:16]}`; BFME1 pointer "
        f"`{(manifest.get('bfme1_pointer') or '?')[:12]}`",
        f"- data_back_rank: {rank['source']}" + (f", inputs from the {rank['inputs']}, objects: {rank['objects']}"
                                                 if rank["source"] == "generated" else ""),
        *component_notes(manifest),
        "",
        "The newest link-cycle prerelease BY MEASUREMENT TIME is the link-cycle figure contributors read; the "
        "committed `reverse/link_cycle/receipt.json` is history (an earlier measurement, no longer updated).",
        "A prerelease: never this repository's Latest release. Immutable: the tag and its assets are never "
        "replaced; a new measurement gets a new tag.",
        "Fetch: `python3 tools/cycle_artifacts.py fetch --latest`. It authenticates this release (designated "
        "publisher, immutable, tag at the measured commit, asset digests from the release API) and reads nothing "
        "from these notes. The queues refuse a bundle measured over 24 h ago (unless `--allow-stale`) or under "
        "other link_cycle rules.",
        ""])


def component_notes(manifest):
    comp = manifest.get("components") or {}
    closure, diff = comp.get("closure_report") or {}, comp.get("cycle_diff") or {}
    lines = []
    if closure.get("included"):
        lines.append(f"- closure report ({closure.get('algorithm')}; {closure.get('graph')}): "
                     f"{closure.get('scored_roots_with_gain')} scored root(s) with a conditional gain; `python3 "
                     "tools/repair_queue.py link --closure --bundle build/cycle_bundles`. Conditional on the frozen "
                     "graph: not a repair proof")
    else:
        lines.append(f"- DIAGNOSTIC-ONLY: no closure report ({closure.get('why')}); the closure queue keeps serving "
                     "the last bundle that has one")
    if diff.get("included") and diff.get("predecessor"):
        lines.append(f"- cycle_diff.json: credit against `{diff['predecessor'].get('tag')}`")
    elif diff.get("included"):
        lines.append("- cycle_diff.json: no predecessor (first published run)")
    else:
        lines.append(f"- cycle_diff.json: not included ({diff.get('why')})")
    return lines


def verify_remote(gh, repo, tag, bundle, files):
    """Every asset uploaded at the bundle's size, and a fresh download hashes to the bundle."""
    info = gh.json(view_cmd(tag, repo)) or {}
    assets = {a.get("name"): a for a in info.get("assets") or ()}
    want = {f.name: f for f in files}
    if set(assets) != set(want):
        raise PublishError(f"the draft holds {sorted(assets)}, the bundle {sorted(want)}")
    for name, path in want.items():
        a = assets[name]
        if a.get("size") != path.stat().st_size or a.get("state", "uploaded") != "uploaded":
            raise PublishError(f"asset {name}: {a.get('size')} bytes, state {a.get('state')}; the bundle has "
                               f"{path.stat().st_size}")
    with tempfile.TemporaryDirectory(prefix="publish_cycle-verify-") as d:
        gh.run(download_cmd(tag, repo, d))
        for name, path in want.items():
            got = Path(d) / name
            if not got.is_file() or ca.sha256_file(got) != ca.sha256_file(path):
                raise PublishError(f"asset {name}: the download does not hash to the bundle's file")
        try:
            ca.validate(d)
        except ca.BundleError as e:
            raise PublishError(f"the downloaded assets do not validate: {e}") from None


def inspect_published(gh, repo, tag, commit, files):
    """The published release of TAG as a consumer will judge it; PublishError naming what is
    wrong. It only reads: a published release is never deleted or rewritten here."""
    held = [r for r in releases_of(gh, repo, tag) if not r.get("draft")]
    if len(held) != 1:
        raise PublishError(f"{len(held)} published release(s) hold {tag}")
    r = held[0]
    if not r.get("prerelease"):
        raise PublishError(f"{tag} is published but is not a prerelease")
    if not ca.publisher_ok(r.get("author")):
        raise PublishError(f"{tag} was published by {(r.get('author') or {}).get('login')!r}, not a designated "
                           f"publisher ({ca.publishers_text()}): consumers refuse it")
    if r.get("target_commitish") != commit:
        raise PublishError(f"{tag} targets {r.get('target_commitish')!r}, not {commit}")
    try:
        at = ca.tag_commit(gh, repo, tag)
    except ca.Refused as e:
        raise PublishError(str(e)) from None
    if at != commit:
        raise PublishError(f"the tag {tag} points at {at!r}, not {commit}")
    if not same_assets(r, files):
        raise PublishError(f"the assets of {tag} are not this bundle's files (digests from the release API)")
    if r.get("immutable") is not True:
        raise PublishError(f"{tag} IS PUBLISHED BUT NOT IMMUTABLE (GitHub reports immutable={r.get('immutable')!r}): "
                           "consumers refuse it. Do not delete or edit it; enable immutable releases and publish "
                           "the next measurement")
    return r


def publish(bundle, repo, *, dry_run=False, gh=None, out=None, root=ROOT, allow_mutable=False, replace_draft=None):
    """Publish BUNDLE as a prerelease; returns {"tag", "commands", ...}. PublishError when refused."""
    out = out or sys.stdout
    bundle = Path(bundle)
    if allow_mutable and not dry_run:
        raise PublishError("--allow-mutable is accepted only with --dry-run")
    try:
        manifest = ca.validate(bundle, root=root)
    except (ca.BundleError, ca.Unavailable) as e:
        raise PublishError(f"{bundle}: {e}") from None
    gh = gh or ca.Gh()
    tag, commit = manifest["tag"], manifest["commit"]
    files = [bundle / name for name in sorted(manifest["members"])] + [bundle / ca.MANIFEST]
    unchecked, warnings = None, []
    me = policy = None
    held, refs = [], []
    try:
        me = gh.json(user_cmd()) or {}
        policy = gh.json(immutable_cmd(repo)) or {}
        held = releases_of(gh, repo, tag)
        refs = [r for r in gh.json(refs_cmd(repo, tag)) or [] if r.get("ref") == f"refs/tags/{tag}"]
    except ca.GhError as e:
        if not dry_run:
            raise
        unchecked = str(e)
    if not unchecked:
        if not ca.publisher_ok(me):
            text = (f"this gh account, {me.get('login')!r} (id {me.get('id')!r}), is not a designated publisher "
                    f"({ca.publishers_text()}, cycle_artifacts.PUBLISHERS): consumers would refuse its release")
            if not dry_run:
                raise PublishError(text)
            warnings.append("A REAL PUBLISH FROM HERE WOULD BE REFUSED: " + text)
        if policy.get("enabled") is not True:
            text = (f"{repo} does not enforce immutable releases (GET /repos/{repo}/immutable-releases: "
                    f"enabled={policy.get('enabled')!r}): a published bundle's assets and tag could be replaced, and "
                    "consumers refuse a mutable release. The maintainer enables it in Settings > General > Releases")
            if not allow_mutable:
                raise PublishError(text)
            warnings.append("--allow-mutable (DRY RUN ONLY): A REAL PUBLISH WOULD BE REFUSED: " + text)
        published = [r for r in held if not r.get("draft")]
        drafts = [r for r in held if r.get("draft")]
        if published:
            if same_assets(published[0], files):
                inspect_published(gh, repo, tag, commit, files)
                print(f"publish_cycle: {tag} is ALREADY PUBLISHED on {repo} (release {published[0].get('id')}) with "
                      "exactly this bundle's assets: nothing to do, nothing changed", file=out)
                return {"tag": tag, "dry_run": dry_run, "already_published": True,
                        "release_id": published[0].get("id"), "commands": []}
            raise PublishError(f"{tag} is already published on {repo} (release {published[0].get('id')}) with OTHER "
                               "assets: a bundle is never overwritten; inspect it by hand")
        if drafts and [d.get("id") for d in drafts] != [replace_draft]:
            raise PublishError(f"{tag} is held by draft release(s) {[d.get('id') for d in drafts]} on {repo} (an "
                               "interrupted publish?): inspect, then pass --replace-draft ID to delete exactly that "
                               "draft and publish; a bundle is never overwritten")
        if replace_draft is not None and not drafts:
            raise PublishError(f"--replace-draft {replace_draft}: no draft release holds {tag}")
        if refs:
            raise PublishError(f"the git tag {tag} already exists on {repo} "
                               f"({(refs[0].get('object') or {}).get('sha', '?')[:12]}) with no published release: a "
                               "bundle is never overwritten; inspect it by hand")
        try:
            remote = (gh.json(commit_cmd(repo, commit)) or {}).get("sha")
        except ca.GhError as e:
            raise PublishError(f"{commit[:12]} is not on {repo} ({e.err.strip()[:200]}): push it first") from None
        if remote != commit:
            raise PublishError(f"{repo} resolves {commit[:12]} to {remote!r}")
    notes_dir = Path(tempfile.mkdtemp(prefix="publish_cycle-notes-"))
    notes = notes_dir / "notes.md"
    notes.write_text(release_notes(manifest), encoding="utf-8", newline="\n")
    title = title_of(manifest)
    plan = ([(delete_cmd(repo, replace_draft), "--replace-draft: only while it is still a draft of this tag")]
            if replace_draft is not None else [])
    plan += [(create_cmd(tag, repo, commit, title, notes),
              "a DRAFT PRERELEASE, never Latest, target the measured commit"),
             (view_cmd(tag, repo), "the draft: a draft prerelease of this tag whose targetCommitish is the full "
                                   "measured commit"),
             (upload_cmd(tag, repo, files), "every member, manifest.json last; never --clobber"),
             (view_cmd(tag, repo), "every asset uploaded at the bundle's size"),
             (download_cmd(tag, repo, "<temporary directory>"), "SHA-256 of every download = the bundle's; it validates"),
             (releases_cmd(repo), "still exactly this draft holds the tag"),
             (refs_cmd(repo, tag), "the git tag still does not exist"),
             (undraft_cmd(tag, repo), "publish: still a prerelease, --latest=false. If this call fails the release "
                                      "is inspected before anything else"),
             (releases_cmd(repo), "published once: prerelease, IMMUTABLE, author a designated publisher, target the "
                                  "measured commit, asset digests = the bundle's files"),
             (ref_cmd(repo, tag), f"the tag (peeled) points at {commit[:12]}")]
    if dry_run:
        print("publish_cycle: DRY RUN: nothing is created, uploaded or published", file=out)
        for line in warnings:
            print(f"  !! {line}", file=out)
        print(f"  bundle  {bundle} (valid; {len(files)} files)", file=out)
        for f in files:
            meta = manifest["members"].get(f.name) or {"size": f.stat().st_size, "sha256": ca.sha256_file(f)}
            print(f"    {meta['size']:>10}  {meta['sha256']}  {f.name}", file=out)
        print("  manifest.json:", file=out)
        for line in (bundle / ca.MANIFEST).read_text(encoding="utf-8").splitlines():
            print(f"    | {line}", file=out)
        if unchecked:
            print(f"  REMOTE CHECKS NOT RUN: gh could not be reached ({unchecked[:300]}). The publisher account, the "
                  f"immutable-release setting, whether {tag} is free and whether {commit[:12]} is on {repo} are "
                  "UNKNOWN; a real publish checks all four first.", file=out)
        else:
            print(f"  account {me.get('login')} (id {me.get('id')}): "
                  + ("a designated publisher" if ca.publisher_ok(me) else "NOT a designated publisher"), file=out)
            print(f"  immutable releases on {repo}: {'enforced' if policy.get('enabled') is True else 'OFF'}", file=out)
            print(f"  tag     {tag}: " + ("held only by the draft --replace-draft names" if replace_draft is not None
                                         else f"no release and no git tag of that name on {repo}"), file=out)
            print(f"  target  {commit}: on {repo}", file=out)
        print(f"  title   {title}", file=out)
        print(f"  notes   {notes} (for people; nothing reads them back):", file=out)
        for line in notes.read_text(encoding="utf-8").splitlines():
            print(f"    | {line}", file=out)
        print("  commands, in order:", file=out)
        for args, why in plan:
            print(f"    {shown(args)}\n        # {why}", file=out)
        print(f"  on a failure before publishing: {shown(delete_cmd(repo, '<draft id>'))}  (this run's own "
              "draft only, and only while it is still a draft; a published release is never touched)", file=out)
        return {"tag": tag, "dry_run": True, "commands": [shown(a) for a, _ in plan], "notes": str(notes),
                "remote_checked": not unchecked, "warnings": warnings}
    try:
        if replace_draft is not None:
            still = [r for r in releases_of(gh, repo, tag) if r.get("id") == replace_draft]
            if len(still) != 1 or not still[0].get("draft"):
                raise PublishError(f"--replace-draft {replace_draft}: it is no longer a draft of {tag}; nothing deleted")
            gh.run(delete_cmd(repo, replace_draft))
            print(f"publish_cycle: deleted the draft {replace_draft} of {tag} (--replace-draft)", file=sys.stderr)
        return _publish(gh, repo, tag, commit, title, notes, bundle, files, out)
    finally:
        shutil.rmtree(notes_dir, ignore_errors=True)


def _publish(gh, repo, tag, commit, title, notes, bundle, files, out):
    release_id, done, published = None, [], False

    def run(args):
        done.append(shown(args))
        return gh.run(args)

    try:
        run(create_cmd(tag, repo, commit, title, notes))
        info = json.loads(run(view_cmd(tag, repo)) or "{}")
        release_id = info.get("databaseId")
        if not release_id or not info.get("isDraft") or not info.get("isPrerelease") or info.get("tagName") != tag:
            raise PublishError(f"the created release is not a draft prerelease of {tag}: {info}")
        print(f"publish_cycle: draft release {release_id} of {tag} on {repo}", file=sys.stderr)
        if info.get("targetCommitish") != commit:
            raise PublishError(f"the draft targets {info.get('targetCommitish')!r}, not the measured commit {commit}")
        run(upload_cmd(tag, repo, files))
        done.append("verify")
        verify_remote(gh, repo, tag, bundle, files)
        same = releases_of(gh, repo, tag)
        if [r.get("id") for r in same] != [release_id]:
            raise PublishError(f"other releases claim {tag}: {[r.get('id') for r in same]}")
        if any(r.get("ref") == f"refs/tags/{tag}" for r in gh.json(refs_cmd(repo, tag)) or []):
            raise PublishError(f"the git tag {tag} appeared while the draft was prepared")
        try:
            run(undraft_cmd(tag, repo))
        except ca.GhError as e:                   # a lost response is not a failure: look before deciding
            now = gh.json(view_cmd(tag, repo)) or {}
            if now.get("isDraft") is not False:
                raise
            print(f"publish_cycle: the un-draft call failed ({str(e)[:200]}) but release {release_id} IS published: "
                  "ambiguous success, resolved by inspection", file=sys.stderr)
        published = True
    except BaseException:
        if release_id is None and done:
            print(f"publish_cycle: a draft of {tag} may remain (its id was never read); inspect with `gh release "
                  f"view {tag} --repo {repo}`; a retry names it and --replace-draft ID removes it", file=sys.stderr)
        if release_id is not None and not published:
            try:
                still = (gh.json(view_cmd(tag, repo)) or {}).get("isDraft")
                if still is True:
                    gh.run(delete_cmd(repo, release_id))
                    print(f"publish_cycle: deleted this run's draft {release_id}", file=sys.stderr)
                else:
                    print(f"publish_cycle: release {release_id} of {tag} is NOT a draft (isDraft={still!r}): it may "
                          "be published. Nothing was deleted; inspect it, and re-run publish (an identical published "
                          "bundle is reported as already published)", file=sys.stderr)
            except Exception as e:               # noqa: BLE001 - report, keep the original failure
                print(f"publish_cycle: the state of release {release_id} of {tag} could not be read ({e}). Nothing "
                      "was deleted. Inspect it before retrying: never delete a published release", file=sys.stderr)
        raise
    inspect_published(gh, repo, tag, commit, files)       # raises, deletes nothing
    print(f"publish_cycle: published {tag} on {repo} (release {release_id}: prerelease, immutable, not Latest)",
          file=out)
    return {"tag": tag, "dry_run": False, "release_id": release_id, "commands": done}


