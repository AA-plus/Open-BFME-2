ROOT = ca.ROOT
FOLD_COLUMNS = ("retail_rva", "retail_start", "export_names", "linked", "symbols", "rule", "verdict")
DIAGNOSTIC_INPUTS = ("reverse/data_ledger.csv", "reverse/exports.csv", "reverse/functions.csv")
RANK_MODES = ("auto", "run-dir", "generate")
VIEW_FIELDS = "databaseId,tagName,isDraft,isPrerelease,targetCommitish,assets"


class RunError(Exception):
    """The run (or the bundle request) is refused."""


def cycle_diff_module():
    """tools/cycle_diff.py when this checkout has it, else None: the comparison is an
    optional component and a bundle is valid without it."""
    try:
        import cycle_diff
    except ImportError:
        return None
    return cycle_diff


class PublishError(Exception):
    """Publication is refused or failed."""


# ---------------------------------------------------------------- validate_run

def _header(path):
    with ca.open_text(path) as handle:
        return tuple(next(csv.reader(handle), ()))


def validate_run(run_dir, *, root=ROOT):
    """Facts of a publishable link_cycle run directory; RunError naming the first fault."""
    run = Path(run_dir)
    rpath = run / "receipt.json"
    if not rpath.is_file():
        refused = (run / "receipt.rejected.json").exists()
        raise RunError(f"{run}: no receipt.json" + (" (receipt.rejected.json: link_cycle refused this run)"
                                                     if refused else ""))
    try:
        receipt = json.loads(rpath.read_text(encoding="utf-8"))
    except ValueError as e:
        raise RunError(f"{rpath}: not JSON ({e})") from None
    if receipt.get("tool") != "link_cycle":
        raise RunError(f"{rpath}: written by {receipt.get('tool')!r}, not link_cycle")
    if receipt.get("authoritative") is not True:
        raise RunError(f"{rpath}: not authoritative (a --measure-only remeasure, a worktree run, a stale warm "
                       "start, a compile failure or an unconverged loop): never published")
    for key in ("moved_during_run", "remeasured_utc"):
        if key in receipt:
            raise RunError(f"{rpath}: carries {key}")
    rejected = run / "receipt.rejected.json"
    if rejected.exists() and rejected.stat().st_mtime > rpath.stat().st_mtime:
        raise RunError(f"{run}: a later run here was rejected (receipt.rejected.json is newer); its outputs may "
                       "have replaced this receipt's")
    commit = receipt.get("commit") or ""
    if len(commit) != 40 or any(c not in "0123456789abcdef" for c in commit):
        raise RunError(f"{rpath}: commit {commit!r} is not a full sha")
    if receipt.get("snapshot") is not True:
        raise RunError(f"{rpath}: not a snapshot run")
    if not receipt.get("core_sha256") or not receipt.get("tool_digest"):
        raise RunError(f"{rpath}: no core_sha256 or tool_digest")
    try:
        core = ca.core_check(receipt, root)
    except ca.BundleError as e:
        raise RunError(str(e)) from None
    series = receipt.get("series") or {}
    status = run / "link_status.csv"
    if not status.is_file():
        raise RunError(f"{run}: no link_status.csv")
    got = ca.sha256_file(status)
    if got != series.get("link_status_sha256"):
        raise RunError(f"{status}: sha256 {got[:16]} is not the receipt's link_status_sha256 "
                       f"{str(series.get('link_status_sha256'))[:16]}: written by another run")
    if _header(status) != STATUS_COLUMNS:
        raise RunError(f"{status}: not link_cycle's per-row header")
    folds = run / "data_fold_list.csv"
    if not folds.is_file():
        raise RunError(f"{run}: no data_fold_list.csv")
    if _header(folds) != FOLD_COLUMNS:
        raise RunError(f"{folds}: not link_cycle's data_fold_list header")
    try:
        measured = ca.measured_of(receipt)
    except ca.BundleError as e:
        raise RunError(f"{rpath}: {e}") from None
    graph = None
    if receipt.get("closure_graph_sha256"):
        graph = run / ca.CLOSURE_GRAPH
        if not graph.is_file() or ca.sha256_file(graph) != receipt["closure_graph_sha256"]:
            raise RunError(f"{graph}: not the closure graph the receipt names (closure_graph_sha256 "
                           f"{receipt['closure_graph_sha256'][:16]})")
    return {"run_dir": run, "receipt": receipt, "commit": commit, "core": receipt["core_sha256"],
            "core_canon": receipt.get("core_canon_sha256"), "core_check": core,
            "tool_digest": receipt["tool_digest"], "rules": receipt.get("rules"),
            "shadow_rules": receipt.get("shadow_rules") or [], "canon_rules": receipt.get("canon_rules"),
            "submodules": receipt.get("submodules") or {},
            "bfme1_pointer": (receipt.get("submodules") or {}).get("reference/open-bfme-1"),
            "status": status, "folds": folds, "status_sha256": got,
            "measured": measured, "graph": graph, "receipt_bytes": rpath.read_bytes()}


# ---------------------------------------------------------------- inputs at the measured commit

def snapshot_proof(snap, receipt):
    """(True, why) when SNAP is the link_cycle snapshot the receipt measured, untouched since:
    its marker names the receipt's commit and tree manifest and a fresh walk (this
    checkout's link_cycle.tree_manifest) agrees."""
    mark = Path(snap) / "SNAPSHOT.json"
    if not mark.is_file():
        return False, f"no snapshot marker at {mark}"
    try:
        meta = json.loads(mark.read_text(encoding="utf-8"))
    except ValueError:
        return False, f"{mark} is not JSON"
    if meta.get("commit") != receipt["commit"]:
        return False, f"{mark} names commit {meta.get('commit')!r}"
    if not meta.get("tree_manifest") or meta.get("tree_manifest") != receipt.get("tree_manifest"):
        return False, f"{mark}'s tree manifest is not the receipt's"
    try:
        walked = ca.link_cycle_module().tree_manifest(snap)
    except Exception as e:                       # noqa: BLE001 - unproven, never assumed
        return False, f"the tree manifest could not be re-walked ({type(e).__name__}: {e})"
    if walked != meta["tree_manifest"]:
        return False, f"{snap} changed since the run (tree manifest {walked[:12]})"
    return True, "marker commit and tree manifest re-proved by a fresh walk"


def measured_inputs(facts, work, *, snapshot_root=None, root=ROOT):
    """{"root", "kind", "basis", "files"}: the diagnostic inputs at the measured commit."""
    receipt, commit = facts["receipt"], facts["commit"]
    snap = Path(snapshot_root) if snapshot_root else facts["run_dir"].resolve().parent.parent
    ok, why = snapshot_proof(snap, receipt)
    if ok:
        base, kind, basis = snap, "snapshot", f"snapshot {snap.name}: {why}"
    elif snapshot_root:
        raise RunError(f"--snapshot-root {snap}: {why}")
    else:
        base, kind, basis = Path(work) / "inputs", "git", f"git show {commit[:12]}:<path> ({why})"
        for rel in DIAGNOSTIC_INPUTS:
            got = subprocess.run(["git", "-C", str(root), "show", f"{commit}:{rel}"], capture_output=True)
            if got.returncode:
                raise RunError(f"the measured commit's {rel} is not readable here "
                               f"({got.stderr.decode('utf-8', 'replace').strip()[:200]}); git fetch, or pass "
                               "--snapshot-root")
            (base / rel).parent.mkdir(parents=True, exist_ok=True)
            (base / rel).write_bytes(got.stdout)
    files = {}
    for rel in DIAGNOSTIC_INPUTS:
        data = ca.text_bytes((base / rel).read_bytes())
        files[rel] = {"text_sha256": hashlib.sha256(data).hexdigest(), "size": len(data)}
    want = (receipt.get("inputs") or {}).get("functions_csv")
    if want and files["reverse/functions.csv"]["text_sha256"] != want:
        raise RunError(f"reverse/functions.csv from the {kind} is not the one the receipt measured "
                       f"({files['reverse/functions.csv']['text_sha256'][:12]} vs {want[:12]})")
    return {"root": base, "kind": kind, "basis": basis, "files": files,
            "cross_check": "reverse/functions.csv equals the receipt's inputs.functions_csv" if want else None}


def _rel(path, start):
    try:
        return os.path.relpath(path, start).replace(os.sep, "/")
    except ValueError:
        return str(path)


def rank_report(facts, inputs, dest, work, *, mode="auto", objects=None, python=None):
    """Write data_back_rank.txt/.json into DEST; returns the manifest's analysis record."""
    run = facts["run_dir"]
    txt, js = run / ca.RANK_TXT, run / ca.RANK_JSON
    if mode in ("auto", "run-dir") and txt.is_file() and js.is_file():
        shutil.copyfile(txt, dest / ca.RANK_TXT)
        shutil.copyfile(js, dest / ca.RANK_JSON)
        return {"source": "run_dir", "note": "taken from the run directory as the producer wrote it; its inputs "
                                             "are not re-proved by this tool"}
    if mode == "run-dir":
        raise RunError(f"--rank run-dir: {run} has no {ca.RANK_TXT} and {ca.RANK_JSON}")
    if objects:
        objects, label = Path(objects), "supplied with --rank-objects (not proven current for the commit)"
    elif inputs["kind"] == "snapshot" and (inputs["root"] / "build" / "match").is_dir():
        objects, label = inputs["root"] / "build" / "match", "the snapshot's build/match (the run's own objects)"
    else:
        objects, label = None, "none (--no-objects: no per-name file counts; owned single-name bindings are of " \
                               "unknown scope)"
    base = inputs["root"]
    tool = Path(__file__).resolve().parent / "data_back_rank.py"     # this checkout's, digested below
    argv = ["--status", "link_status.csv", "--folds", "data_fold_list.csv",
            "--ledger", str(base / "reverse/data_ledger.csv"), "--functions", str(base / "reverse/functions.csv"),
            "--exports", str(base / "reverse/exports.csv"), "--json", str(dest / ca.RANK_JSON)]
    argv += ["--objects", _rel(objects, run), "--cache", str(Path(work) / "rank_objects.pkl")] if objects \
        else ["--no-objects"]
    env = dict(os.environ, PYTHONIOENCODING="utf-8", PYTHONDONTWRITEBYTECODE="1")
    got = subprocess.run([python or sys.executable, str(tool), *argv], cwd=run, capture_output=True, env=env)
    if got.returncode:
        raise RunError(f"data_back_rank exited {got.returncode}: "
                       f"{got.stderr.decode('utf-8', 'replace').strip()[-800:]}")
    (dest / ca.RANK_TXT).write_bytes(got.stdout.replace(b"\r\n", b"\n"))
    shown = []
    for a in argv:
        for old, new in ((str(base), "<measured>"), (str(dest), "<bundle>"), (str(work), "<scratch>")):
            a = a.replace(old, new)
        shown.append(a.replace(os.sep, "/"))
    return {"source": "generated", "tool": "tools/data_back_rank.py", "tool_text_sha256": ca.text_sha256(tool),
            "argv": shown, "cwd": "<run_dir>", "inputs": inputs["kind"], "objects": label}


