#!/usr/bin/env python3
"""Publish one link_cycle run as an immutable GitHub prerelease bundle.

The producer is the designated measuring machine (the maintainer's laptop
watchdog); consumers fetch and authenticate with tools/cycle_artifacts.py, whose
module text states the bundle's identity, members and trust rules. Nothing is
committed to master.

  validate RUN_DIR
      The run is publishable: receipt.json exists, was written by link_cycle,
      is `authoritative` and was not superseded by a later rejected run in the
      same directory; link_status.csv is the file the receipt hashed, with
      link_cycle's header; data_fold_list.csv is there with its header; when
      the receipt names a closure graph (closure_graph_sha256) the run holds
      that file. When this checkout's link_cycle has the receipt's tool digest
      the receipt core is recomputed.
  bundle RUN_DIR --out DIR --producer LABEL [--previous DIR | --first]
      One flat directory, written beside DIR and renamed into place once it
      validates (an existing DIR is refused):
        receipt.json, link_status.csv.gz, data_fold_list.csv.gz
        data_back_rank.txt/.json   --rank auto: the run directory's own when
            both are there (inputs not re-proved), else generated by this
            checkout's tools/data_back_rank.py with the ledgers AT THE MEASURED
            COMMIT (a proven snapshot's, else `git show <commit>:<path>`).
        closure_graph.json.gz      when the receipt names it: the graph the
            measure judged, as link_cycle wrote it.
        closure_roots.json.gz, closure_blockers.csv.gz   the closure report
            (tools/closure_report.py graph, or replay for a run measured before
            link_cycle wrote its graph) from --closure DIR, else the run
            directory. It must name this run. A bundle WITHOUT one is refused
            unless --diagnostic-only: such a bundle is published as a
            measurement, says so, and the closure queue keeps serving the last
            bundle that has a report.
        cycle_diff.json            tools/cycle_diff.py's report against the
            previous PUBLISHED measurement (--previous: a run or bundle
            directory), or its no-predecessor report (--first), written by
            cycle_diff.dumps. Left out, with the reason, without either flag.
        manifest.json              schema, tag, full commit, the measurement
            instance, producer, every figure the receipt gives repeated for
            reading (and checked against it), rules/tool/analysis digests,
            diagnostic input hashes and SHA-256 + size of every member.
  publish BUNDLE [--repo OWNER/REPO] [--dry-run [--allow-mutable]] [--replace-draft ID]
      Refused unless: this gh account is a designated publisher
      (cycle_artifacts.PUBLISHERS); the repository enforces immutable releases;
      the measured commit is on the repository; and the tag is free. A
      PUBLISHED release already on the tag is inspected, never touched: when
      its assets are byte for byte this bundle's (digests from the release
      API) the publish already happened and this run reports so (exit 0);
      otherwise it is refused. A DRAFT on the tag (an interrupted run) is
      refused and named; --replace-draft ID deletes exactly that draft, only
      while it is still a draft, and goes on.
      Then: a DRAFT PRERELEASE (--latest=false, --target the full measured
      commit; the draft's target is checked), every file uploaded (never
      --clobber), each asset's size and the SHA-256 of a fresh download checked
      against the bundle, the tag re-checked as unclaimed, and only then the
      un-draft. If the un-draft call fails the release is INSPECTED: when it is
      published the run goes on to the checks below (a lost response is not a
      failure); a published release is never deleted or rewritten. After
      publication: prerelease, not a draft, immutable, authored by a designated
      publisher, the tag at the measured commit, and the API's asset digests
      equal to the bundle's files.
      --dry-run runs only read-only checks and prints the members, the manifest
      and the exact commands. --allow-mutable is accepted ONLY with --dry-run.

  python3 tools/publish_cycle.py validate ~/lcs/275a758e4c/build/link_cycle
  python3 tools/closure_report.py graph ~/lcs/<sha10>/build/link_cycle --out ~/lcs/<sha10>/build/link_cycle
  python3 tools/publish_cycle.py bundle ~/lcs/<sha10>/build/link_cycle --out build/cycle_bundle_<sha10> \\
          --producer bfme-laptop/link-cycle-watchdog --previous build/cycle_bundles/<id>/bundle   # or --first
  python3 tools/publish_cycle.py publish build/cycle_bundle_<sha10> --dry-run
"""
import argparse
import csv
import gzip
import hashlib
import json
import os
import shlex
import shutil
import subprocess
import sys
