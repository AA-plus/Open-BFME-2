def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    v = sub.add_parser("validate", help="is a link_cycle run directory publishable")
    v.add_argument("run_dir")
    b = sub.add_parser("bundle", help="write the bundle for a run")
    b.add_argument("run_dir")
    b.add_argument("--out", required=True, help="the bundle directory (must not exist, or be empty)")
    b.add_argument("--producer", required=True, help="who measured: a host/user label, e.g. bfme-laptop/watchdog")
    b.add_argument("--rank", choices=RANK_MODES, default="auto",
                   help="data_back_rank: the run directory's own if present (auto), required from it, or generated")
    b.add_argument("--snapshot-root", help="the link_cycle snapshot the run measured (default: RUN_DIR/../..)")
    b.add_argument("--rank-objects", help="objects for the generated data_back_rank (default: the snapshot's)")
    b.add_argument("--closure", metavar="DIR", help="closure_roots.json and closure_blockers.csv of this run "
                                                    "(tools/closure_report.py replay; default: RUN_DIR when there)")
    b.add_argument("--previous", metavar="DIR", help="the previous published run (a run or bundle directory): "
                                                     "embed tools/cycle_diff.py's credit comparison")
    b.add_argument("--first", action="store_true", help="no predecessor: embed cycle_diff's first-run report")
    b.add_argument("--diagnostic-only", action="store_true",
                   help="publish a measurement WITHOUT a closure report (refused otherwise); the manifest says so")
    p = sub.add_parser("publish", help="publish a bundle as a GitHub prerelease")
    p.add_argument("bundle")
    p.add_argument("--repo", default=ca.DEFAULT_REPO)
    p.add_argument("--dry-run", action="store_true", help="read-only checks; print the commands")
    p.add_argument("--allow-mutable", action="store_true",
                   help="ONLY with --dry-run: go on when the repository does not enforce immutable releases")
    p.add_argument("--replace-draft", type=int, metavar="ID",
                   help="delete exactly this DRAFT release holding the bundle's tag (an interrupted run), then publish")
    args = ap.parse_args(argv)
    try:
        if args.cmd == "validate":
            f = validate_run(args.run_dir)
            print(f"publishable: {f['run_dir']}")
            print(f"  commit        {f['commit']}")
            print(f"  receipt core  {f['core']} ({f['core_check']})")
            print(f"  tool digest   {f['tool_digest']}")
            print(f"  rules         {f['rules']} shadow {f['shadow_rules']} canon {f['canon_rules']}")
            print(f"  BFME1 pointer {f['bfme1_pointer']}")
            print(f"  measured      {f['measured']['start_utc']} .. {f['measured']['end_utc']}")
            print(f"  link_status   {f['status_sha256']} = the receipt's")
            print(f"  closure graph {'in the run, bound by the receipt' if f['graph'] else 'none (measured before link_cycle wrote it: closure_report.py replay)'}")
            print(f"  tag           {ca.tag_for(f['receipt_bytes'])}")
            return 0
        if args.cmd == "bundle":
            m = make_bundle(args.run_dir, args.out, args.producer, rank=args.rank, snapshot_root=args.snapshot_root,
                            rank_objects=args.rank_objects, closure=args.closure, previous=args.previous,
                            first=args.first, require_closure=not args.diagnostic_only)
            print(f"bundle {m['tag']} at {args.out}: {len(m['members']) + 1} files; data_back_rank "
                  f"{m['analysis']['data_back_rank']['source']}; inputs {m['diagnostic_inputs']['basis']}")
            for key, c in m["components"].items():
                print(f"  {key}: " + ("included" if c.get("included") else f"NOT included ({c.get('why')})"))
            return 0
        if args.allow_mutable and not args.dry_run:
            raise PublishError("--allow-mutable is accepted only with --dry-run: a real publish to a repository "
                               "without immutable releases is refused")
        publish(args.bundle, args.repo, dry_run=args.dry_run, allow_mutable=args.allow_mutable,
                replace_draft=args.replace_draft)
        return 0
    except (RunError, PublishError, ca.BundleError, ca.Refused) as e:
        print(f"publish_cycle: refused: {e}", file=sys.stderr)
        return 1
    except ca.Unavailable as e:
        print(f"publish_cycle: unavailable: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
